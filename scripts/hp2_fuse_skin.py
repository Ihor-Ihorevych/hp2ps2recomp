"""Fuse Harry Potter 2's VU1 skinning programs (entries 1C28, 1D60, 1E10, 1E88, 1EE0) into one function for hp2_vu1_skin.cpp.

The generated (vurecomp, fast mode) lazy bodies of the five programs are taken verbatim, with kSticky = false, and joined: one set
of register locals for all of them, each body's prologue turned into a re-entry block (the clamped shadows recomputed from the raw
registers and the flag pipeline restarted, as a fresh call of that program would do after the hop wrote the registers back), and
every way out that hops to one of the five entries replaced by a jump to that block. Any other way out writes every register back
and returns the address (the chain loop goes on there).
"""
import glob, re, sys

SRC = sys.argv[1]   # folder with work-*/src/*.cpp of a fast-mode live run (PS2_VU_LIVE_KEEP=1)
OUT = sys.argv[2]
ENTRIES = {0x1C28: '42D6E9811029E540', 0x1D60: 'DBBD1B44AFD983D1', 0x1E10: 'A7B0B0B00784674F', 0x1E88: 'ECDBBCCBC548F551',
           0x1EE0: 'A04B3E566A765F4D'}

files = glob.glob(SRC + '/work-*/src/*.cpp')
text = {}
for f in files:
    s = open(f, encoding='utf-8', errors='replace').read()
    for e, k in ENTRIES.items():
        if e in text:
            continue
        m = re.search(r'template <bool kSticky>\nPS2_VU_BODY void vu1_%s_b\(.*?\n\}\n' % k, s, re.S)
        if m:
            text[e] = m.group(0)
missing = [hex(e) for e in ENTRIES if e not in text]
if missing:
    sys.exit('missing bodies: %s' % missing)

decl_vf, decl_n, decl_i = set(), set(), set()
blocks = []
for e in sorted(ENTRIES):
    body = text[e]
    body = body.split('{\n', 1)[1].rsplit('\n}\n', 1)[0]  # inside the function
    tag = 'B%04X_' % e
    lines = body.split('\n')
    pro, rest = [], []
    in_pro = True
    for l in lines:
        if in_pro and l.startswith('    goto L_'):
            in_pro = False
            rest.append(l)
            continue
        (pro if in_pro else rest).append(l)
    enter = []
    for l in pro:
        l = l.strip()
        if not l or l.startswith('(void)'):
            continue
        m = re.match(r'Reg128 (vf\d+|vacc) = r\.(vf\[\d+\]|acc);', l)
        if m:
            decl_vf.add((m.group(1), m.group(2)))
            continue
        m = re.match(r'v4u (n\w+) = (vshadow\(\w+\));', l)
        if m:
            decl_n.add(m.group(1))
            enter.append('%s = %s;' % (m.group(1), m.group(2)))
            continue
        m = re.match(r'std::uint16_t (i\d+) = r\.vi\[(\d+)\];', l)
        if m:
            decl_i.add((m.group(1), m.group(2)))
            continue
        if l.startswith('FlagPipeV fl;'):
            enter.append('fl = FlagPipeV{};')
            continue
        if l.startswith('fl.start(r);'):
            enter.append('fl.start(r);')
            continue
        if l.startswith('bool pend = false'):
            enter.append('pend = false, pendj = false, ending = false;')
            continue
        if l.startswith('std::uint32_t jpc = 0;'):
            enter.append('jpc = 0;')
            continue
        if l.startswith('const std::uint32_t sh ='):
            continue  # sh = 0: the programs run at the addresses they were made at
        raise SystemExit('unexpected prologue line in %04X: %s' % (e, l))
    code = '\n'.join(rest)
    code = code.replace('kSticky', 'false')
    code = re.sub(r'\bL_([0-9A-F]{4})\b', tag + r'L_\1', code)
    code = code.replace('dispatch:', tag + 'dispatch:').replace('goto dispatch;', 'goto ' + tag + 'dispatch;')
    # every way out: fl.finish(r) (the flags into the register file, as the hop did), then the next program
    def exit_sub(m):
        return '{ fl.finish(r); next = %s; goto route; }' % m.group(1)
    # an exit is "<syncs> vhop(hop, EXPR);\n    return;" ; the syncs (fl.finish, r.vi[] = , r.vf[] = , flushes) are dropped: the locals stay
    code = re.sub(r'\n[^\n]*?vhop\(hop, ([^;]*?)\);\n\s*return;', lambda m: '\n    ' + exit_sub(m), code)
    if 'vhop' in code or 'return' in code:
        raise SystemExit('an exit of %04X was not rewritten' % e)
    blocks.append((e, tag, enter, code))

out = []
out.append('// Generated by fuse_skin.py from the vurecomp output of the five programs (do not edit by hand; see hp2_vu1.cpp for the design).')
out.append('std::uint32_t skin_fused(Vu0Regs &__restrict__ r, std::uint8_t *mem) {')
out.append('    const std::uint32_t sh = 0;')
out.append('    (void)sh;')
out.append('    FlagPipeV fl;')
out.append('    bool pend = false, pendj = false, ending = false;')
out.append('    std::uint32_t jpc = 0, next = 0;')
out.append('    (void)pend; (void)pendj; (void)ending; (void)jpc;')
allvf = sorted(decl_vf, key=lambda x: (x[0] == 'vacc', int(x[0][2:]) if x[0] != 'vacc' else 99))
for name, src in allvf:
    out.append('    Reg128 %s = r.%s;' % (name, src))
for n in sorted(decl_n):
    out.append('    v4u %s{};' % n)
alli = sorted(decl_i, key=lambda x: int(x[1]))
for name, idx in alli:
    out.append('    std::uint16_t %s = r.vi[%s];' % (name, idx))
out.append('    goto B1C28_enter;')
for e, tag, enter, code in blocks:
    out.append('%senter:' % tag)
    out.append('    ' + ' '.join(enter))
    out.append(code)
out.append('route:')
out.append('    switch (next) {')
for e, tag, enter, code in blocks:
    if e != 0x1C28:
        out.append('    case 0x%04Xu: fl.start(r); goto %senter_again;' % (e, tag))
out.append('    default: break;')
out.append('    }')
sync = ' '.join('r.%s = %s;' % (src, name) for name, src in allvf) + ' ' + ' '.join('r.vi[%s] = %s;' % (idx, name) for name, idx in alli)
out.append('    ' + sync)
out.append('    return next;')
out.append('}')
res = '\n'.join(out)
# the re-entry of an internal hop: the flags were put into the register file (fl.finish) and are read again by the enter block's
# fl.start; "enter_again" is the enter block itself
for e, tag, enter, code in blocks:
    res = res.replace(tag + 'enter_again', tag + 'enter')
res = res.replace('case 0x', 'case 0x').replace('fl.start(r); goto', 'goto')
open(OUT, 'w', encoding='utf-8', newline='\n').write(res + '\n')
print('fused', len(blocks), 'programs,', len(res.splitlines()), 'lines,', len(allvf), 'vector registers,', len(alli), 'integer registers')
